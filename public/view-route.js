const locatorKeys = ['scope', 'group', 'asset', 'frame', 'element'];

export function viewerBase(pathname) {
  return pathname.match(/^\/(?:p|i)\/[A-Za-z0-9_-]+\//)?.[0] ?? '/';
}

export function isViewPath(pathname) {
  return pathname.startsWith('/view/');
}

export function readViewRoute(url) {
  const query = url.searchParams;
  const path = url.pathname.slice(viewerBase(url.pathname).length);
  const explicitScope = query.get('scope');
  const asset = query.get('asset'), group = query.get('group');
  if (explicitScope || asset || group) {
    return {
      scope: explicitScope ?? (asset ? `asset:${asset}` : `group:${group}`),
      target: asset || group ? { path: asset, group, form: query.get('frame'), element: query.has('element') ? { id: query.get('element') } : null } : null,
      onlyFrame: asset && !explicitScope ? query.get('frame') : null,
      isolated: true,
      strict: !explicitScope,
    };
  }
  if (path.startsWith('view/')) {
    const match = /^view\/(?:all|layer\/([^/]+))(?:\/(group|asset)\/([^/]+)(?:\/frame\/([^/]+)(?:\/element\/([^/]+))?)?)?\/?$/.exec(path);
    if (!match) throw Error('Invalid design path. Use a link generated by SDG.');
    const [layer, kind, key, frame, element] = match.slice(1).map(value => value === undefined ? null : decodeURIComponent(value));
    if (kind !== 'asset' && frame) throw Error('A frame needs an asset path.');
    return {
      scope: layer ? `layer:${layer}` : 'all',
      target: kind ? { path: kind === 'asset' ? key : null, group: kind === 'group' ? key : null, form: frame, element: element ? { id: element } : null } : null,
      strict: true,
    };
  }
  return { scope: 'default', target: null };
}

export function viewURL(base, scope, target = {}, { isolated = false, onlyFrame = null } = {}) {
  const url = new URL(base);
  url.pathname = viewerBase(url.pathname);
  for (const key of locatorKeys) url.searchParams.delete(key);
  const { path, group, form, element } = target;
  if (onlyFrame) {
    url.searchParams.set('asset', path);
    url.searchParams.set('frame', onlyFrame);
    if (element?.id != null) url.searchParams.set('element', element.id);
  } else if (isolated || !['all', 'layer'].includes(scope.split(':', 1)[0])) {
    url.searchParams.set('scope', scope);
    if (path) url.searchParams.set('asset', path);
    else if (group) url.searchParams.set('group', group);
    if (path && form) url.searchParams.set('frame', form);
    if (path && form && element?.id != null) url.searchParams.set('element', element.id);
  } else {
    const segments = ['view', ...(scope === 'all' ? ['all'] : ['layer', scope.slice('layer:'.length)])];
    if (path) segments.push('asset', path);
    else if (group) segments.push('group', group);
    if (path && form) segments.push('frame', form);
    if (path && form && element?.id != null) segments.push('element', element.id);
    url.pathname += segments.map(encodeURIComponent).join('/');
  }
  return url;
}
